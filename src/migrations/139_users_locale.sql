-- 139: язык пользователя для транзакционных писем.
--
-- Нужен для английской версии (promo-music.ru/en): человек, заполнивший
-- форму регистрации по-английски, должен получить письмо верификации
-- по-английски, а не по-русски.
--
-- ⚠️ Почему НЕ переиспользуем существующую users.language: она про язык
-- ТРЕКА и заполнена дефолтом — 'en' у 3407 из 3409 аккаунтов, 'ru' у двух.
-- Если бы письма читали её, все действующие русские артисты немедленно
-- начали бы получать англоязычные письма. Поэтому отдельная колонка с
-- дефолтом 'ru': текущая база — русская, и молчаливое переключение языка
-- для неё было бы регрессией.
--
-- Значение проставляется при регистрации из языка интерфейса
-- (см. auth-routes.tsx, поле locale в теле запроса).

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS locale varchar(5) NOT NULL DEFAULT 'ru';

-- Индекс не нужен: колонка читается только по уже найденному пользователю
-- (по id или email), выборок «все англоязычные» в продукте нет.

COMMENT ON COLUMN users.locale IS
  'Язык интерфейса при регистрации (ru|en). Используется для писем. Не путать с users.language — там язык трека.';
