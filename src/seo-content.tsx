<p>Не пишите через два дня "вы получили мой трек?". Плейлист-комитет соберётся в среду или четверг. Если трек подходит, через неделю-полторы вы либо услышите его в эфире, либо получите ответ. Если через три недели тишина, можно отправить вежливое напоминание. Один раз. Не больше.</p>

