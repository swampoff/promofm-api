/**
 * PRICING — единый источник цены публикации.
 *
 * Владелец 2026-08-07: цену поднимаем с 7 000 до 10 000 ₽, но не сразу —
 * артистам дали время до 1 сентября (об этом ушла рассылка). Поэтому цена
 * вычисляется по дате, а не хардкодится: до порога 7 000, после 10 000.
 *
 * ВАЖНО: цена фиксируется в треке (payment_amount) в момент одобрения, так
 * что треки, одобренные до 1 сентября, останутся с 7 000 даже если оплата
 * пройдёт позже. Это осознанно: обещали старую цену — держим.
 */

/** Момент перехода: 1 сентября 2026, 00:00 МСК */
export const PRICE_SWITCH_AT = Date.parse('2026-09-01T00:00:00+03:00');

export const PUBLICATION_PRICE_OLD = 7000;
export const PUBLICATION_PRICE_NEW = 10000;

/** Актуальная цена публикации трека/микса на текущий момент. */
export function getPublicationPrice(at: number = Date.now()): number {
  return at >= PRICE_SWITCH_AT ? PUBLICATION_PRICE_NEW : PUBLICATION_PRICE_OLD;
}
